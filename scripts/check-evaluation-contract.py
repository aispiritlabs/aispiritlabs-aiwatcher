#!/usr/bin/env python3
"""Regenerate or check the Evaluation wire schema, without adding an HTTP route."""

import argparse
import json
from pathlib import Path
import subprocess


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    result = subprocess.run(
        ["cargo", "run", "--quiet", "--locked", "-p", "aiwatcher-evaluation", "--example", "schema"],
        cwd=root, capture_output=True, text=True, check=True,
    ).stdout
    fixture = json.loads((root / "contracts/fixtures/evaluation-v1/manifest.json").read_text())
    consumer = (
        '// Generated by scripts/check-evaluation-contract.py from the shared fixture.\n'
        'import type { EvaluationManifest, JudgeConfiguration } from "../src/evaluation";\n\n'
        'const manifest = ' + json.dumps(fixture, indent=2) + ' satisfies EvaluationManifest;\n\n'
        'const judge: JudgeConfiguration = {\n'
        '  provider: "fixture", model: manifest.context.scorer,\n'
        '  configuration: manifest.variant.generation_config,\n'
        '  calibration_dataset: manifest.context.dataset,\n'
        '};\n'
        'const withJudge: EvaluationManifest = { ...manifest, context: { ...manifest.context, judge } };\n'
        '// @ts-expect-error An unsupported schema must not compile.\n'
        'const future: EvaluationManifest = { ...withJudge, schema_version: 2 };\n'
        '// @ts-expect-error A metric must declare its direction and aggregation.\n'
        'withJudge.context.metrics = [{ name: "accuracy", unit: "ratio" }];\n'
    )
    outputs = {
        root / "contracts/evaluation-manifest.schema.json": result,
        root / "sdk/typescript/tests/evaluation-contract.ts": consumer,
    }
    for path, content in outputs.items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        elif not path.exists() or path.read_text() != content:
            print(f"{path.relative_to(root)} is stale; run rtk proxy python3 scripts/check-evaluation-contract.py --write")
            return 1
    print("Evaluation manifest contract is current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
